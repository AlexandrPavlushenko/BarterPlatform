from rest_framework import permissions


class IsOwnerOnly(permissions.BasePermission):
    """Кастомное разрешение, позволяющее доступ только владельцу объекта.

    Проверяет, является ли пользователь, делающий запрос (request.user),
    автором объекта (obj.author). Разрешение применяется для:
    - Проверки доступа к конкретному объекту
    - Ограничения действий (изменение/удаление) только для владельцев

    Пример использования:
    - Разрешить редактирование объявления только его автору
    - Ограничить удаление комментария только создателю комментария

    Возвращает:
        bool: True если пользователь является автором, False в противном случае
    """

    def has_object_permission(self, request, view, obj):
        """Проверяет права доступа к конкретному объекту.

        Args:
            request: Запрос от пользователя
            view: View, обрабатывающий запрос
            obj: Проверяемый объект (должен иметь поле author)

        Returns:
            bool: Результат проверки прав доступа
        """
        return obj.author == request.user
