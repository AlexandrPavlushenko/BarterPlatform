from django.contrib import admin

from users.models import User


@admin.register(User)
class UserAdmin(admin.ModelAdmin):
    """Настройки админ-панели для модели пользователя.

    Позволяет администраторам:
    - Просматривать список пользователей с ключевыми полями
    - Быстро изменять статус активности пользователя
    - Осуществлять поиск по email и фамилии

    Атрибуты:
        list_display: Определяет поля, отображаемые в списке пользователей
        list_editable: Поля, доступные для редактирования прямо в списке
        search_fields: Поля, по которым работает поиск в админке
    """

    # Поля для отображения в списке пользователей
    list_display = (
        "id",  # ID пользователя
        "email",  # Электронная почта (логин)
        "first_name",  # Имя
        "last_name",  # Фамилия
        "phone",  # Телефон
        "avatar",  # Аватар (отображается как ссылка)
        "city",  # Город
        "is_active",  # Статус активности
    )

    # Поля, доступные для редактирования в общем списке
    list_editable = ("is_active",)  # Возможность быстро блокировать/разблокировать

    # Поля для поиска пользователей
    search_fields = (
        "email",  # Поиск по полному или частичному email
        "last_name",  # Поиск по фамилии
    )
